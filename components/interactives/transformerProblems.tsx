function ClampFigure(phase: number) {
  const cx = 240;
  const cy = 132;
  return (
    <g>
      <circle cx={cx} cy={cy} r={62} fill="none" stroke={C.mut} strokeWidth={16} opacity={0.32} />
      {Array.from({ length: 16 }, (_, i) => {
        const a = (i / 16) * 2 * Math.PI;
        return (
          <line
            key={i}
            x1={cx + 52 * Math.cos(a)}
            y1={cy + 52 * Math.sin(a)}
            x2={cx + 72 * Math.cos(a)}
            y2={cy + 72 * Math.sin(a)}
            stroke={C.ok}
            strokeWidth={2.2}
          />
        );
      })}
      <circle cx={cx} cy={cy} r={13} fill="none" stroke={C.warn} strokeWidth={3} />
      <SvgTex x={cx} y={cy - 8} tex={String.raw`I_1`} color={C.warn} fontSize={13} width={20} anchor="middle" />
      <SvgTex x={cx + 92} y={cy - 60} tex={String.raw`N_2=2000`} color={C.ok} fontSize={13} width={78} />
      <SvgTex x={cx - 92} y={cy - 60} tex={String.raw`N_1=1`} color={C.warn} fontSize={13} width={52} anchor="end" />

      {phase >= 1 && (
        <>
          <line x1={cx + 74} y1={cy + 30} x2={396} y2={cy + 30} stroke={C.ok} strokeWidth={2.2} />
          <circle cx={410} cy={cy + 30} r={16} fill="none" stroke={C.ok} strokeWidth={2.2} />
          <SvgTex x={410} y={cy + 22} tex="\text{A}" color={C.ok} fontSize={13} width={20} anchor="middle" />
        </>
      )}
      {phase >= 2 && (
        <SvgTex
          x={cx}
          y={cy + 96}
          tex={String.raw`N_1I_1=N_2I_2`}
          color={C.wire}
          fontSize={15}
          width={110}
          anchor="middle"
        />
      )}
    </g>
  );
}

