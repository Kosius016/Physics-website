/** Схематичен трансформатор: две намотки върху общо ядро. */
function MiniTransformer({
  phase,
  n1,
  n2,
  loadLabel,
}: {
  phase: number;
  n1: string;
  n2: string;
  loadLabel?: string;
}) {
  const x = 150;
  const y = 70;
  const w = 180;
  const h = 130;
  const t = 22;
  const coil = (cx: number, color: string, count: number) =>
    Array.from({ length: count }, (_, i) => (
      <ellipse
        key={i}
        cx={cx}
        cy={y + t + 16 + i * ((h - 2 * t - 32) / (count - 1 || 1))}
        rx={18}
        ry={7}
        fill="none"
        stroke={color}
        strokeWidth={2.2}
      />
    ));

  return (
    <g>
      <path
        d={`M ${x} ${y} h ${w} v ${h} h ${-w} Z
            M ${x + t} ${y + t} v ${h - 2 * t} h ${w - 2 * t} v ${-(h - 2 * t)} Z`}
        fillRule="evenodd"
        fill={C.mut}
        opacity={0.26}
        stroke={C.mut}
        strokeWidth={1.4}
      />
      {coil(x + t / 2, C.warn, 6)}
      {coil(x + w - t / 2, C.ok, 4)}

      <g stroke={C.warn} strokeWidth={2.2} fill="none">
        <path d={`M ${x + t / 2 - 18} ${y + 40} H 74`} />
        <path d={`M ${x + t / 2 - 18} ${y + h - 40} H 74`} />
        <path d={`M 74 ${y + 40} V ${y + h - 40}`} />
      </g>
      <g stroke={C.ok} strokeWidth={2.2} fill="none">
        <path d={`M ${x + w - t / 2 + 18} ${y + 40} H 408`} />
        <path d={`M ${x + w - t / 2 + 18} ${y + h - 40} H 408`} />
        {phase >= 1 && <path d={`M 408 ${y + 40} V ${y + h - 40}`} />}
      </g>

      <SvgTex x={70} y={y + 76} tex={n1} color={C.warn} fontSize={13} width={54} anchor="end" />
      <SvgTex x={414} y={y + 76} tex={n2} color={C.ok} fontSize={13} width={54} />
      {phase >= 1 && loadLabel && (
        <SvgTex x={414} y={y + h - 34} tex={loadLabel} color={C.ok} fontSize={12.5} width={58} />
      )}
      {phase >= 2 && (
        <SvgTex
          x={x + w / 2}
          y={y + h / 2 - 10}
          tex="\Phi"
          color={C.minus}
          fontSize={15}
          width={20}
          anchor="middle"
        />
      )}
    </g>
  );
}

