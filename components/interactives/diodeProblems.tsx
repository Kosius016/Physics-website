const VD = 0.7;

/** Малък диод: триъгълникът сочи към чертата. */
function Dio({ x, y, angle, on }: { x: number; y: number; angle: number; on: boolean }) {
  const color = on ? C.ok : C.mut;
  return (
    <g>
      {on && <circle cx={x} cy={y} r={15} fill={C.ok} opacity={0.18} />}
      <g transform={`translate(${x} ${y}) rotate(${angle})`}>
        <polygon points="-8,-7 -8,7 5,0" fill={color} />
        <line x1={5} y1={-8.5} x2={5} y2={8.5} stroke={color} strokeWidth={2.4} />
      </g>
    </g>
  );
}

function Caps({ x, y, text, color = C.mut }: { x: number; y: number; text: string; color?: string }) {
  return (
    <text x={x} y={y} fill={color} fontFamily={DRAWING_FONT_FAMILY} fontSize={12} fontWeight={600} letterSpacing="0.07em">
      {text}
    </text>
  );
}

/** Мостовата схема с двете шини; `live` казва коя двойка е осветена. */
function BridgeFigure({ live, showCap }: { live: 0 | 1 | 2; showCap: boolean }) {
  const railTop = 58;
  const railBot = 206;
  const legL = 120;
  const legR = 240;
  const node = 132;
  const loadX = showCap ? 392 : 330;
  const capX = 330;
  return (
    <g>
      <g stroke={C.wire} strokeWidth={2} fill="none">
        <path d={`M ${legL} ${railTop} H ${loadX}`} />
        <path d={`M ${legL} ${railBot} H ${loadX}`} />
        <path d={`M ${legL} ${railTop} V ${railBot}`} />
        <path d={`M ${legR} ${railTop} V ${railBot}`} />
        <path d={`M ${legL} ${node} H ${legL + 24}`} />
        <path d={`M ${legR - 24} ${node} H ${legR}`} />
        <path d={`M ${loadX} ${railTop} V ${(railTop + railBot) / 2 - 26}`} />
        <path d={`M ${loadX} ${(railTop + railBot) / 2 + 26} V ${railBot}`} />
      </g>
      <circle cx={(legL + legR) / 2} cy={node} r={14} fill={STAGE_BG} stroke={C.warn} strokeWidth={2.2} />
      <path
        d={`M ${(legL + legR) / 2 - 9} ${node} q 4.5 -8 9 0 q 4.5 8 9 0`}
        fill="none"
        stroke={C.warn}
        strokeWidth={1.9}
      />
      <Dio x={legL} y={(railTop + node) / 2} angle={-90} on={live === 1} />
      <Dio x={legR} y={(railTop + node) / 2} angle={-90} on={live === 2} />
      <Dio x={legL} y={(node + railBot) / 2} angle={-90} on={live === 2} />
      <Dio x={legR} y={(node + railBot) / 2} angle={-90} on={live === 1} />
      <rect
        x={loadX - 13}
        y={(railTop + railBot) / 2 - 26}
        width={26}
        height={52}
        fill={STAGE_BG}
        stroke={C.wire}
        strokeWidth={2}
      />
      {showCap && (
        <g stroke={C.minus} strokeWidth={2.4} fill="none">
          <path d={`M ${capX} ${railTop} V ${(railTop + railBot) / 2 - 7}`} />
          <path d={`M ${capX - 15} ${(railTop + railBot) / 2 - 7} H ${capX + 15}`} />
          <path d={`M ${capX - 15} ${(railTop + railBot) / 2 + 7} H ${capX + 15}`} />
          <path d={`M ${capX} ${(railTop + railBot) / 2 + 7} V ${railBot}`} />
        </g>
      )}
      <SvgTex x={legL - 36} y={(railTop + node) / 2} tex="D_1" color={C.mut} fontSize={12} width={28} />
      <SvgTex x={legR + 10} y={(railTop + node) / 2} tex="D_2" color={C.mut} fontSize={12} width={28} />
      <SvgTex x={legL - 36} y={(node + railBot) / 2} tex="D_3" color={C.mut} fontSize={12} width={28} />
      <SvgTex x={legR + 10} y={(node + railBot) / 2} tex="D_4" color={C.mut} fontSize={12} width={28} />
      <SvgTex x={loadX + 16} y={(railTop + railBot) / 2} tex="R_{\text{т}}" color={C.mut} fontSize={12.5} width={36} />
      {showCap && <SvgTex x={capX - 52} y={(railTop + railBot) / 2} tex="C" color={C.minus} fontSize={13} width={22} />}
      <Caps x={60} y={40} text="ОТ ТРАНСФОРМАТОРА" />
    </g>
  );
}

